def narrative_claim_issues(text: str) -> list[str]:
    """Catch explicit guarantees/threats; not a general truth or style classifier."""
    clauses = re.split(r"[.!?。！？\n]|지만|그러나|하지만", text)
    patterns = (
        r"(?:반드시|무조건|틀림없이|확실히).{0,30}(?:성공|합격|결혼|재회|당첨|부자|수익|돈이|귀인)",
        r"(?:곧|올해|내년|이번\s*달|\d{1,2}월).{0,20}(?:귀인|운명의\s*상대|옛\s*연인).{0,12}(?:나타납니다|찾아옵니다|돌아옵니다|만납니다)",
        r"(?:놓치면|지금.{0,8}결제하지\s*않으면).{0,20}(?:평생|불행|재앙|불운)",
        r"(?:수익|합격|결혼|재회|성공)(?:을|이|은|는)?\s*(?:보장됩니다|보장합니다|확정입니다|정해져\s*있습니다)",
    )
    for clause in clauses:
        for pattern in patterns:
            match = re.search(pattern, clause)
            if not match:
                continue
            # Permit an explicit rejection of a claim, not an unrelated disclaimer.
            tail = clause[match.end():]
            if re.search(r"(?:보장|단정|확정|예측|뜻|의미|말)할?\s*수\s*없|(?:보장|단정|확정|예측|뜻|의미)하지\s*않|(?:라는|다는|이라는)\s*(?:뜻|의미|보장).{0,8}아닙", tail):
                continue
            return ["확정 예언 또는 공포 유도 표현"]
    return []


def jargon_density_issues(text: str) -> list[str]:
    """Flag dense technical chains, without rewriting potentially wrong facts."""
    terms = r"지장간|본기|월지|일지|지지|천간|일간|십신|비견|겁재|식신|상관|편재|정재|편관|정관|편인|정인|[갑을병정무기경신임계][목화토금수]|[자축인묘진사오미신유술해][목화토금수]"
    for sentence in re.split(r"[.!?。！？\n]+", text):
        # Avoid treating ordinary Korean words such as '상관없다' as jargon.
        hits = re.findall(rf"(?<![가-힣])(?:{terms})(?=$|[^가-힣]|은|는|이|가|의|을|를|인|과|와|으로)", sentence)
        if len(hits) >= 5:
            return ["전문용어 과밀: 계산 경로 대신 생활 장면과 쉬운 해석으로 재작성"]
    return []
